function getIcon(provider: OAuthProvider) {
  switch (provider) {
    case "google": return <GoogleIcon />;
    case "github": return <GitHubIcon />;
    case "notion": return <NotionIcon />;
    default: return null;
  }
}

export function OAuthButton({ provider, mode = "signin", iconOnly = false, className }: OAuthButtonProps) {
  const [loading, setLoading] = useState(false);
  const supabase = createClient();
  const config = providerConfig[provider];

  const handleOAuthSignIn = async () => {
    setLoading(true);

    const { error } = await supabase.auth.signInWithOAuth({
      provider: provider as Provider,
      options: {
        redirectTo: `${window.location.origin}/auth/callback`,
      },
    });

    if (error) {
      console.error(`${config.name} sign-in error:`, error);
      setLoading(false);
    }
  };

  if (iconOnly) {
    return (
      <Button
        type="button"
        variant="outline"
        size="icon"
        onClick={handleOAuthSignIn}
        disabled={loading}
        title={`Continue with ${config.name}`}
        className={cn("w-12 h-12", className)}
      >
        {loading ? (
          <Spinner size="sm" className="text-muted-foreground" />
        ) : (
          getIcon(provider)
        )}
      </Button>
    );
  }

  const buttonText = loading
    ? "Connecting..."
    : mode === "signin"
    ? `Continue with ${config.name}`
    : `Sign up with ${config.name}`;

  return (
    <Button
      type="button"
      variant="outline"
      onClick={handleOAuthSignIn}
      disabled={loading}
      className={cn("w-full", className)}
    >
      {loading ? (
        <Spinner size="sm" className="text-muted-foreground mr-2" />
      ) : (
        <span className="mr-2">{getIcon(provider)}</span>
      )}
      {buttonText}
    </Button>
  );
}
